import {readFile,mkdir,writeFile,readdir} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {build} from 'esbuild';
const root=fileURLToPath(new URL('../',import.meta.url));
const assets={};
const types={'.html':'text/html; charset=utf-8','.js':'text/javascript; charset=utf-8','.css':'text/css; charset=utf-8','.svg':'image/svg+xml','.txt':'text/plain; charset=utf-8','.zip':'application/zip'};
async function collect(directory,prefix=''){
  for(const file of await readdir(directory,{withFileTypes:true})){
    if(file.name.startsWith('.')||file.name==='server')continue;
    const location=path.join(directory,file.name);const key=prefix+'/'+file.name;
    if(file.isDirectory())await collect(location,key);
    else if(path.extname(file.name)==='.zip')assets[key]={base64:(await readFile(location)).toString('base64'),contentType:types['.zip']};
    else assets[key]={body:await readFile(location,'utf8'),contentType:types[path.extname(file.name)]||'text/plain; charset=utf-8'};
  }
}
await collect(path.join(root,'dist'));
await mkdir(path.join(root,'worker'),{recursive:true});
await writeFile(path.join(root,'worker','assets.mjs'),`// Generated by scripts/build.mjs\nexport default ${JSON.stringify(assets)};\n`);
await mkdir(path.join(root,'dist','server'),{recursive:true});
await build({entryPoints:[path.join(root,'worker','index.mjs')],outfile:path.join(root,'dist','server','index.js'),bundle:true,format:'esm',platform:'browser',target:'es2022',minify:true,legalComments:'eof'});
await mkdir(path.join(root,'dist','.openai'),{recursive:true});
let hosting={d1:'DB',r2:null};
try{hosting=JSON.parse(await readFile(path.join(root,'.openai','hosting.json'),'utf8'));}catch(error){if(error.code!=='ENOENT')throw error;}
await writeFile(path.join(root,'dist','.openai','hosting.json'),JSON.stringify(hosting,null,2)+'\n');
console.log('Built Pirce Watch hosted worker and assets.');
